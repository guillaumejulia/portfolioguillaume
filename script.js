// The screenshot window is a real gallery: all controls change the selected capture.
let screenshotIndex = 0;
function updateScreenshotViewer() {
    const viewer = document.getElementById('screenshot-viewer');
    if (!viewer) return;
    const captures = commonProjectData['6'].gallery;
    const selected = captures[screenshotIndex];
    const img = viewer.querySelector('img');
    img.src = selected.src;
    img.alt = 'Groovexe — ' + selected[currentLang];
    viewer.querySelector('.viewer-caption').textContent = selected[currentLang];
    viewer.querySelector('.viewer-count').textContent = String(screenshotIndex + 1).padStart(2, '0') + ' / ' + String(captures.length).padStart(2, '0');
    viewer.querySelectorAll('[data-viewer-step]').forEach(button => {
        button.setAttribute('aria-label', translations[currentLang][Number(button.dataset.viewerStep) < 0 ? 'viewer-prev' : 'viewer-next']);
    });
}
document.querySelectorAll('[data-viewer-step]').forEach(button => {
    button.addEventListener('click', () => {
        screenshotIndex = (screenshotIndex + Number(button.dataset.viewerStep) + commonProjectData['6'].gallery.length) % commonProjectData['6'].gallery.length;
        updateScreenshotViewer();
    });
});

