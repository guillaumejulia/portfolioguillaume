function loadProjectDetails() {
    const id = new URLSearchParams(location.search).get('id');
    const common = Object.hasOwn(commonProjectData, id) ? commonProjectData[id] : null;
    const details = common ? projectsDetails[id][currentLang] : null;
    const title = document.getElementById('project-title');
    if (!title) return;
    if (!details) {
        title.textContent = translations[currentLang]['not-found'];
        document.title = title.textContent + ' | Guillaume Julia';
        return;
    }
    title.textContent = projectNames[id];
    document.title = projectNames[id] + ' | Guillaume Julia';
    document.getElementById('project-date').textContent = details.date;
    let intro = document.getElementById('project-intro');
    if (!intro) {
        intro = document.createElement('p');
        intro.id = 'project-intro';
        title.parentElement.append(intro);
    }
    intro.textContent = details.intro || '';
    intro.hidden = !details.intro;
    const tags = document.getElementById('tags');
    tags.replaceChildren(...common.tags.map(tag => {
        const span = document.createElement('span');
        span.textContent = tag;
        return span;
    }));
    const video = document.getElementById('video-container');
    if (!video.firstElementChild) {
        const wrapper = document.createElement('div');
        wrapper.className = 'video-wrapper';
        const iframe = document.createElement('iframe');
        iframe.src = `https://www.youtube.com/embed/${common.videoId}?rel=0`;
        iframe.allow = 'encrypted-media; picture-in-picture; fullscreen';
        iframe.allowFullscreen = true;
        wrapper.append(iframe);
        video.append(wrapper);
    }
    video.querySelector('iframe').title = translations[currentLang]['video-label'] + ' — ' + projectNames[id];
    let gallery = document.getElementById('project-gallery');
    if (!gallery) {
        gallery = document.createElement('div');
        gallery.id = 'project-gallery';
        video.after(gallery);
    }
    gallery.replaceChildren();
    (common.gallery || []).forEach(item => {
        const figure = document.createElement('figure');
        const image = document.createElement('img');
        image.src = item.src;
        image.alt = projectNames[id] + ' — ' + item[currentLang];
        image.loading = 'lazy';
        const caption = document.createElement('figcaption');
        caption.textContent = item[currentLang];
        figure.append(image, caption);
        gallery.append(figure);
    });
    const container = document.getElementById('features-container');
    container.replaceChildren();
    details.features.forEach((feature, index) => {
        const section = document.createElement('section');
        const img = common.imgs[index];
        section.className = 'feature-block' + (img ? '' : ' text-only');
        const heading = featureTitles[currentLang][id]?.[index] || feature.title;
        section.innerHTML = `<div class="feature-text"><span class="note-label">${String(index + 1).padStart(2, '0')} / ${projectNames[id]}</span><h2>${heading}</h2><p>${feature.desc}</p></div>`;
        if (img) {
            const figure = document.createElement('figure');
            figure.className = 'feature-image';
            const image = document.createElement('img');
            image.src = img;
            image.alt = `${projectNames[id]} — ${heading}`;
            image.loading = 'lazy';
            const caption = document.createElement('figcaption');
            caption.textContent = `${projectNames[id]} / ${heading}`;
            figure.append(image, caption);
            section.append(figure);
        }
        container.append(section);
    });
}

function updateContent() {
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-key]').forEach(element => {
        const value = translations[currentLang][element.dataset.key];
        if (value) element.innerHTML = value;
    });
    const toggle = document.getElementById('lang-toggle');
    toggle.textContent = currentLang === 'fr' ? 'FR / EN' : 'EN / FR';
    toggle.setAttribute('aria-label', currentLang === 'fr' ? 'Switch to English' : 'Passer en français');
    updateScreenshotViewer();
    if (document.getElementById('project-title')) loadProjectDetails();
    else document.title = currentLang === 'fr' ? 'Guillaume Julia | Carnet de développement' : 'Guillaume Julia | Development notebook';
}

document.getElementById('lang-toggle').addEventListener('click', () => {
    currentLang = currentLang === 'fr' ? 'en' : 'fr';
    try { localStorage.setItem('site-lang', currentLang); } catch { /* Optional persistence. */ }
    updateContent();
});
updateContent();
